// Parsed once into lists of lit [x, y] pixels.
const GLYPHS = {};
for (const [ch, rows] of Object.entries(SOURCE)) {
  const pixels = [];
  rows.split(' ').forEach((row, y) => {
    for (let x = 0; x < GLYPH_W; x++) if (row[x] === '#') pixels.push([x, y]);
  });
  GLYPHS[ch] = pixels;
}

export const textWidth = (text, scale = 1) => Math.max(0, text.length * ADVANCE - 1) * scale;

// Draws text with its top-left at (x, y). `shadow` draws a 1-pixel offset copy.
export function drawText(ctx, text, x, y, { scale = 1, color = '#fff', shadow = null, align = 'left' } = {}) {
  const str = String(text).toUpperCase();
  const cx = Math.round(align === 'right' ? x - textWidth(str, scale) : align === 'center' ? x - textWidth(str, scale) / 2 : x);
  const cy = Math.round(y);
  const pass = (ox, oy, fill) => {
    ctx.fillStyle = fill;
    let px = cx;
    for (const ch of str) {
      const glyph = GLYPHS[ch] || GLYPHS['?'];
      for (const [gx, gy] of glyph) ctx.fillRect(px + gx * scale + ox, cy + gy * scale + oy, scale, scale);
      px += ADVANCE * scale;
    }
  };
  if (shadow) pass(scale, scale, shadow);
  pass(0, 0, color);
}
